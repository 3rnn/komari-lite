import assert from "node:assert/strict";
import test from "node:test";
import * as model from "../script/glass-network-summary.mjs";
import { readFileSync } from "node:fs";
import { jsx } from "react/jsx-runtime";
import { act, create } from "react-test-renderer";
import { summaryRenderer, summaryContext } from "./fixtures/glass-summary-render.mjs";
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const now = Date.parse("2026-10-23T12:00:00Z");
const node = (time, speed = 5, extra = {}) => ({ uuid: "a", name: "edge", online: true, net_out: speed, net_in: 3, updated_at_live: new Date(time).toISOString(), ...extra });
test("sparkline records only observed fresh public aggregate rates, bounded to sixty seconds and samples", () => {
  assert.equal(typeof model.observeGlassThroughput, "function");
  let history = [];
  for (let i = 0; i < 100; i++) history = model.observeGlassThroughput(history, [node(now + i * 1000), { ...node(now + i * 1000, 10), uuid: "b" }, node(now, 999, { hidden: true })], now + i * 1000, true);
  assert.equal(history.length, 60);
  assert.equal(history[0].time, now + 40_000);
  assert.equal(history.at(-1).value, 21);
  const unchanged = model.observeGlassThroughput(history, [node(now + 99_000), { ...node(now + 99_000, 10), uuid: "b" }], now + 99_500, true);
  assert.deepEqual(unchanged, history, "never repeat a frozen feed as invented history");
});
test("sparkline preserves honest gaps, same-second bounds, zero and empty states", () => {
  let h = model.observeGlassThroughput([], [node(now)], now);
  h = model.observeGlassThroughput(h, [node(now + 500, 0)], now + 500);
  assert.equal(h.length, 1);
  assert.equal(h[0].value, 3);
  h = model.observeGlassThroughput(h, [], now + 1000);
  h = model.observeGlassThroughput(h, [node(now + 2000)], now + 2000, false);
  h = model.observeGlassThroughput(h, [node(now + 3000)], now + 3000);
  assert.equal(h[1].value, null);
  assert.equal(typeof model.glassThroughputPaths, "function");
  assert.equal(model.glassThroughputPaths(h, now + 3000).length, 2, "missing observations split paths");
  assert.equal(model.glassThroughputPaths([{ time: now, value: 2 }, { time: now + 5000, value: 7 }], now + 5000).length, 2, "feed silence is not interpolated");
  assert.deepEqual(model.glassThroughputPaths([], now), []);
  assert.deepEqual(model.glassThroughputPaths(h, now + 70_000), []);
  assert.equal(model.observeGlassThroughput([], [node(now, 0, { net_in: 0 })], now)[0].value, 0);
});

test("a brief hidden or missing interval cannot be bridged within one sample bucket or replay cached data", () => {
  let history = model.observeGlassThroughput([], [node(now)], now);
  history = model.observeGlassThroughput(history, [node(now + 1000)], now + 1000);
  history = model.observeGlassThroughput(history, [], now + 1100, false);
  const before = history;
  history = model.observeGlassThroughput(history, [node(now + 1000)], now + 1200);
  assert.deepEqual(history, before, "resuming cannot re-observe the cached pre-hide feed");
  history = model.observeGlassThroughput(history, [node(now + 1300)], now + 1300);
  assert.equal(model.glassThroughputPaths(history, now + 1300).length, 2, "same-second gap must survive bucket replacement");
});

test("actual shipped streaming hook records feed only and gaps hidden intervals with cleanup", async () => {
  const dist = new URL("../../backend/web/public/bundledThemes/Glass/dist/", import.meta.url);
  const index = readFileSync(new URL("index.html", dist), "utf8");
  const code = readFileSync(new URL(`_next/static/chunks/${index.match(/3859ru-[a-f0-9]{8}\.js/)[0]}`, dist), "utf8");
  let clock = now;
  class Clock extends Date { static now() { return clock; } }
  const listeners = new Map(), timers = new Map();
  let id = 0;
  const document = { hidden: false, addEventListener: (event, fn) => listeners.set(event, fn), removeEventListener: event => listeners.delete(event) };
  const context = summaryContext([node(clock)]);
  const Summary = summaryRenderer(code, context, { Date: Clock, document, setTimeout: (fn, delay) => { timers.set(++id, { fn, delay }); return id; }, clearTimeout: id => timers.delete(id) });
  let tree;
  await act(() => { tree = create(jsx(Summary, {})); });
  const chart = () => tree.root.findByProps({ className: "overview-network-chart" });
  assert.equal(chart().props["data-sample-count"], 1);
  clock += 1000;
  context.nodes = [node(clock, 9)];
  await act(() => tree.update(jsx(Summary, {})));
  assert.equal(chart().props["data-sample-count"], 2);
  assert.equal(tree.root.findAllByType("path").length, 1);
  clock += 1000;
  document.hidden = true;
  await act(() => listeners.get("visibilitychange")());
  clock += 1000;
  context.nodes = [node(clock, 99)];
  await act(() => tree.update(jsx(Summary, {})));
  assert.equal(chart().props["data-sample-count"], 2, "hidden rates must not be observed");
  document.hidden = false;
  await act(() => listeners.get("visibilitychange")());
  clock += 1000;
  context.nodes = [node(clock, 11)];
  await act(() => tree.update(jsx(Summary, {})));
  assert.equal(chart().props["data-sample-count"], 3);
  assert.equal(tree.root.findAllByType("path").length, 2, "resuming never bridges hidden time");
  clock += 60_001;
  const pending = [...timers.values()]; timers.clear();
  await act(() => pending.forEach(timer => timer.fn()));
  assert.equal(chart().props["data-sample-count"], 0);
  assert.equal(tree.root.findAllByType("path").length, 0);
  await act(() => tree.unmount());
  assert.equal(listeners.size, 0);
  assert.equal(timers.size, 0);
});
